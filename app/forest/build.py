"""Bundle Memory Forest's scene scripts for AnkiNX, and make sample forests to try them with.

  python3 app/forest/build.py

writes app/resources/forest/forest.js (src/shim.js, the add-on's scripts from
app/library/memory-forest/web in the order its catalog.py loads them, then src/runner.js),
app/resources/forest/presets.json (its sceneries, which the app offers) and
app/forest/samples/<preset>.json (the add-on's made-up test forest in each of them, as
its render checks draw it, for forest_bench). Run it after fetching a new pin of the add-on
(tools/fetch_frontend_deps.sh) or changing src/; the outputs are committed.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
ADDON = os.path.join(APP, "library", "memory-forest")
WEB = os.path.join(ADDON, "web")
OUT = os.path.join(APP, "resources", "forest")
sys.path.insert(0, ADDON)

import catalog  # noqa: E402
import fake_forest  # noqa: E402
import forest_data  # noqa: E402
import milestones  # noqa: E402
import presets  # noqa: E402
import scene  # noqa: E402

# The add-on's page, not its scenes: the heatmap draws under the forest, and the runner has no
# pointer, caption or zoom (they only define functions, but the heatmap is a sixth of the size).
LEFT_OUT = ("calendar.js", "heatmap/")
# The sample forests: this many days of trees, on this day at noon (the render checks' day)
SAMPLE_TREES = 300
SAMPLE_NOW = dt.datetime(2026, 9, 19, 12)


def scripts() -> list:
    files = [f for f in catalog.SCRIPTS if not f.startswith(LEFT_OUT)]
    for kind in catalog.KINDS:
        folder = os.path.join(WEB, kind)
        files += [f"{kind}/{n}" for n in sorted(os.listdir(folder)) if n.endswith(".js")]
    return files


def visitor_text() -> dict:
    """Each animal's name and why it came, in English: the add-on's Python sends them to its page
    (milestones.for_page), the Rust port doesn't."""
    en = json.load(open(os.path.join(ADDON, "locales", "en.json"), encoding="utf-8"))
    return {k: {"name": en[milestones.NAMES[k]], "stayed": en[milestones.STAYED[k]]} for k in milestones.NAMES}


def preset_list() -> list:
    """The sceneries the app offers (Settings > About), each the five settings its preset stands
    for, in the add-on's order: the app passes them to the Rust port, which makes the mood."""
    def season(p) -> dict | None:
        # (a seasonal one: only in its week, from the year it arrives - presets.unlocked)
        if not p.season:
            return None
        first, starts, ends = p.season
        return {"first": first.isoformat(), "from": list(starts), "to": list(ends)}
    return [{"key": p.key, "label": p.label, "environment": p.environment, "landscape": p.landscape,
             "landmark": p.landmark, "weather": p.weather, "time": p.time, "season": season(p)}
            for p in presets.FOREST_PRESETS if p.key != presets.DAILY]


def bundle() -> str:
    pin = open(os.path.join(ADDON, ".pinned-sha"), encoding="utf-8").read().split()[0]
    parts = [f"// Generated by app/forest/build.py from app/forest/src and Memory Forest {pin[:12]}"
             " (https://github.com/baraklevy20/memory-forest, MIT). Do not edit."]
    parts.append(open(os.path.join(HERE, "src", "shim.js"), encoding="utf-8").read())
    parts.append(f"globalThis.__forestVisitors = {json.dumps(visitor_text(), ensure_ascii=False)};")
    for rel in scripts():
        parts.append(f"// ---- memory-forest/web/{rel}")
        parts.append(open(os.path.join(WEB, rel), encoding="utf-8").read())
    parts.append(open(os.path.join(HERE, "src", "runner.js"), encoding="utf-8").read())
    return "\n".join(parts)


def sample(preset) -> dict:
    mood = scene.choose_mood(preset.values(), SAMPLE_NOW)
    f = forest_data.merge_old(fake_forest.make(SAMPLE_TREES))
    return {"trees": f["trees"], "stats": f["stats"], "visitors": f["visitors"], "merged": f.get("merged"),
            "forestSeed": f["forest_seed"], "anniversaries": [0], "events": [], "journal": "",
            "mood": mood, "environmentName": preset.label, "animations": True, "testForest": True}


def main() -> None:
    os.makedirs(os.path.join(HERE, "samples"), exist_ok=True)
    with open(os.path.join(OUT, "forest.js"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(bundle())
    # (MIT: its notice goes wherever its code does)
    with open(os.path.join(ADDON, "LICENSE"), encoding="utf-8") as src, \
            open(os.path.join(OUT, "LICENSE-memory-forest.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(src.read())
    with open(os.path.join(OUT, "presets.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(preset_list(), fh, indent=1)
    keys = []
    for p in presets.FOREST_PRESETS:
        if p.key == presets.DAILY:
            continue
        with open(os.path.join(HERE, "samples", f"{p.key}.json"), "w", encoding="utf-8", newline="\n") as fh:
            json.dump(sample(p), fh, separators=(",", ":"))
        keys.append(p.key)
    print("forest.js:", os.path.getsize(os.path.join(OUT, "forest.js")), "bytes; samples:", " ".join(keys))


if __name__ == "__main__":
    main()
