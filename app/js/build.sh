#!/usr/bin/env bash
# Bundle the card script runtime (src/runtime.js with linkedom and jQuery)
# into app/resources/script/runtime.js for QuickJS. Run inside WSL. Needs
# Node (installed by tools/js_toolchain.sh). The bundle is committed, so app
# builds never need Node; run this after changing app/js.
set -euo pipefail
source "$(dirname "$0")/../../tools/env.sh"
PATH="$(bash "$ANKISWITCH_SRC/tools/js_toolchain.sh"):$PATH"
WORK="$ANKISWITCH_WORK/js"
mkdir -p "$WORK"
rsync -a --delete --exclude /node_modules/ --exclude /runtime.js --exclude /runtime-licenses.txt --exclude /meta.json "$ANKISWITCH_SRC/app/js/" "$WORK/"
cd "$WORK"
if [[ -f package-lock.json ]]; then
    npm ci --no-audit --no-fund --loglevel=error
else
    npm install --no-audit --no-fund --loglevel=error
fi
# Whitespace and syntax only: names stay, so errors in the log stay readable.
npx esbuild src/runtime.js --bundle --format=iife --platform=neutral --target=es2022 \
    --main-fields=module,main --minify-whitespace --minify-syntax --legal-comments=eof \
    --banner:js="// Generated by app/js/build.sh from app/js/src, linkedom $(node -p "require('linkedom/package.json').version") and jQuery $(node -p "require('jquery/package.json').version"). Do not edit." \
    --log-level=warning --metafile=meta.json --outfile=runtime.js
node licenses.mjs meta.json > runtime-licenses.txt
# Saved with the lock file npm may have updated, which belongs in the repo too.
cp runtime.js runtime-licenses.txt "$ANKISWITCH_SRC/app/resources/script/"
cp package-lock.json "$ANKISWITCH_SRC/app/js/package-lock.json"
ls -l "$ANKISWITCH_SRC/app/resources/script/runtime.js"
